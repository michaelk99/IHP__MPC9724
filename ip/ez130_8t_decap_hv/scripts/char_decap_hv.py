# Description: characterize the HV decaps -> liberty corners + LV comparison
#
# A decap has no arc: the liberty is area, leakage and pg pins. Measured here,
# against the EZ130 LV cell of the same width:
#
#   C     series C of the cell across the rail at 1 MHz
#   leak  the DC supply current x VDD
#
# Not the RC corner: PSP runs quasi-static, so an AC sweep reports the full C
# at any frequency whatever the channel length (doc/decap_hv.md §3).
#
# Run inside iic-osic-tools:
#   python3 char_decap_hv.py           # table + lib/*.lib for tt/ss/ff
#   python3 char_decap_hv.py --table   # table only

import argparse
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "..", "..", "scripts"))
import spicerun                                                  # noqa: E402

LIB = "ez130_8t_decap_hv"
HV_CDL = os.path.join(ROOT, "cdl", LIB + ".cdl")
LV_CDL = os.path.join(ROOT, "..", "ez130_8t_v1p1", "cdl", "ez130_8t.cdl")
LV_LIB = os.path.join(ROOT, "..", "ez130_8t_v1p1", "lib")
PDK = os.path.join(os.environ.get("PDK_ROOT", "/foss/pdks"),
                   os.environ.get("PDK", "ihp-sg13cmos5l"))
MODELS = os.path.join(PDK, "libs.tech/ngspice/models")

# section, VDD, T, EZ130 corner tag: the 1.2 V sign-off family (CLAUDE.md)
CORNERS = {
    "tt": ("mos_tt", 1.20, 25, "tt_1p20v_25c"),
    "ss": ("mos_ss", 1.08, 125, "ss_1p08v_125c"),
    "ff": ("mos_ff", 1.32, -40, "ff_1p32v_m40c"),
}
PAIRS = (("DECAPHV8", "DECAP8"), ("DECAPHV16", "DECAP16"), ("DECAPHV32", "DECAP32"))
F = 1e6

DECK = """* decap probe {cell} {corner}
{libs}
{inc}
.temp {temp}
Vdd vdd 0 dc {vdd} ac 1
{inst}
.control
op
print i(vdd)
ac lin 1 {f} {f}
print i(vdd)
.endc
.end
"""


def subckt(path, cell):
    """One .subckt as X-cards: sg13_*_*mos are subcircuits, not models."""
    keep, out = False, []
    for line in open(path):
        low = line.lower()
        if low.startswith(".subckt "):
            keep = line.split()[1] == cell
        if keep:
            out.append("X" + line if low[:1] == "m" else line)
            if low.startswith(".ends"):
                break
    if not out:
        raise SystemExit("no .subckt %s in %s" % (cell, path))
    return "".join(out)


def run(cell, corner, hv):
    sect, vdd, temp, _ = CORNERS[corner]
    lib = os.path.join(MODELS, "cornerMOShv.lib" if hv else "cornerMOSlv.lib")
    deck = DECK.format(cell=cell, corner=corner, libs=".lib %s %s" % (lib, sect),
                       inc=subckt(HV_CDL if hv else LV_CDL, cell), temp=temp,
                       vdd=vdd, inst="Xc vdd vdd 0 0 %s" % cell, f=F)
    r = spicerun.run_deck(deck, tag=cell)
    num = r"([-+]?[\d.]+(?:e[-+]?\d+)?)"
    dc = re.search(r"^i\(vdd\)\s*=\s*%s\s*$" % num, r.out, re.M)
    ac = re.search(r"^i\(vdd\)\s*=\s*%s,%s\s*$" % (num, num), r.out, re.M)
    if not (dc and ac):
        sys.stderr.write(r.out[-2000:])
        raise SystemExit("%s %s: no result" % (cell, corner))
    y = -complex(float(ac.group(1)), float(ac.group(2)))    # into the cell
    return {"leak": abs(float(dc.group(1))) * vdd * 1e9,     # nW, EZ130's unit
            "c": -1e15 / (2 * math.pi * F * (1 / y).imag)}   # fF, Z = ESR + 1/jwC


def area(cell):
    lef = open(os.path.join(ROOT, "lef", LIB + ".lef")).read()
    i = lef.index("MACRO %s\n" % cell)
    w, h = re.search(r"SIZE ([\d.]+) BY ([\d.]+)", lef[i:]).groups()
    return float(w) * float(h)


def liberty_leak(cell, corner):
    text = open(os.path.join(LV_LIB, "ez130_8t_%s.lib" % CORNERS[corner][3])).read()
    i = text.index("cell (%s)" % cell)
    j = text.index("cell_leakage_power", i)
    return float(text[j:text.index(";", j)].split(":")[1])


def table(corners):
    rows = {}
    print("%-9s %-3s %9s %13s %12s %13s" % ("cell", "", "C [fF]", "C/A [fF/um2]",
                                            "leak [nW]", "liberty [nW]"))
    for corner in corners:
        for hv, lv in PAIRS:
            a = area(hv)
            for cell, is_hv in ((lv, False), (hv, True)):
                m = run(cell, corner, is_hv)
                ref = "-" if is_hv else "%.4g" % liberty_leak(cell, corner)
                print("%-9s %-3s %9.2f %13.3f %12.4g %13s"
                      % (cell, corner, m["c"], m["c"] / a, m["leak"], ref))
                rows[(cell, corner)] = m
    return rows


LIB_HEAD = """/* SPDX-FileCopyrightText: 2026 Harald Pretl, Johannes Kepler University
 * SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1
 * Generated by ip/{lib}/scripts/char_decap_hv.py -- do not edit.
 * cell_leakage_power is the DC supply current x VDD in ngspice. The HV PSP
 * models carry no gate tunnelling term (iginvlw = 0), so what is left is
 * junction and solver residue, not a leakage estimate.
 */
library ({name}) {{
  delay_model : table_lookup;
  capacitive_load_unit (1,pf);
  current_unit : "1mA";
  leakage_power_unit : "1nW";
  pulling_resistance_unit : "1kohm";
  time_unit : "1ns";
  voltage_unit : "1V";
  default_cell_leakage_power : 0;
  nom_process : 1;
  nom_temperature : {temp};
  nom_voltage : {vdd};
  voltage_map (VDD, {vdd});
  voltage_map (VSS, 0);
  voltage_map (VNW, {vdd});
  voltage_map (VPW, 0);
  operating_conditions ({op}) {{
    process : 1;
    temperature : {temp};
    voltage : {vdd};
  }}
  default_operating_conditions : {op};
"""

LIB_CELL = """  cell ({cell}) {{
    area : {area:.4f};
    cell_footprint : "decap";
    cell_leakage_power : {leak:.4g};
    dont_touch : true;
    dont_use : true;
    is_decap_cell : true;
    pg_pin (VDD) {{
      pg_type : primary_power;
      voltage_name : "VDD";
    }}
    pg_pin (VSS) {{
      pg_type : primary_ground;
      voltage_name : "VSS";
    }}
    leakage_power () {{
      value : {leak:.4g};
      related_pg_pin : VDD;
    }}
  }}
"""


def liberty(corner, rows):
    _, vdd, temp, tag = CORNERS[corner]
    op = "PVT_%sV_%sC" % (("%.2f" % vdd).replace(".", "P"),
                          ("M%d" % -temp) if temp < 0 else temp)
    name = "%s_%s" % (LIB, tag)
    body = [LIB_HEAD.format(lib=LIB, name=name, vdd=vdd, temp=temp, op=op)]
    for hv, _ in PAIRS:
        body.append(LIB_CELL.format(cell=hv, area=area(hv), leak=rows[(hv, corner)]["leak"]))
    body.append("}\n")
    path = os.path.join(ROOT, "lib", name + ".lib")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write("".join(body))
    print("WROTE %s" % path)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("corner", nargs="*", choices=sorted(CORNERS))
    ap.add_argument("--table", action="store_true", help="write no liberty")
    a = ap.parse_args()
    corners = a.corner or ["tt", "ss", "ff"]
    rows = table(corners)
    if not a.table:
        for corner in corners:
            liberty(corner, rows)


if __name__ == "__main__":
    main()

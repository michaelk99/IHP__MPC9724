"""Write the include of the hold MC bench: the two EZ130 cells and the four macro SPEF nets of the path.

    python3 gen_bench.py <out.spice> [rc_scale]

rc_scale defaults to 1.2, the max RC of verification/reports/sta_rc_corners. Coupling caps are grounded, load pins outside the bench are their ff liberty pin caps.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../../.."))
EZ = os.path.join(REPO, "ip/ez130_8t_v1p1")
SPEF = os.path.join(REPO, "macros/dsa1_dig/final/spef/nom/dsa1_dig_top.nom.spef")
LIB = os.path.join(EZ, "lib/ez130_8t_ff_1p32v_m40c.lib")
sys.dont_write_bytecode = True  # keep ip/ clean
sys.path.insert(0, os.path.join(EZ, "scripts"))
from cdl2spice import convert  # noqa: E402

CELLS = ("DFFRQX1", "BUFX12")
# SPEF instance name to bench instance: common buffer, the two leaves, launch and capture flop.
BENCH = {"clkbuf_1_0__f_clk_regs": "xcom", "clkbuf_leaf_17_clk_regs": "xl17",
         "clkbuf_leaf_16_clk_regs": "xl16", "_20056_": "xlau", "_20057_": "xcap"}
# Nets by driver pin.
DRIVERS = ("clkbuf_1_0__f_clk_regs:Y", "clkbuf_leaf_17_clk_regs:Y",
           "clkbuf_leaf_16_clk_regs:Y", "_20056_:Q")


def cells():
    txt, _ = convert(open(os.path.join(EZ, "cdl/ez130_8t.cdl")).read())
    out = []
    for c in CELLS:
        m = re.search(r"^\.SUBCKT %s .*?^\.ENDS" % c, txt, re.M | re.S)
        for line in m.group(0).splitlines():
            if line.startswith("X") and "sg13_lv_" in line:
                line += " mm_ok=1"
            out.append(line)
    return "\n".join(out)


def pin_caps():
    caps, cell, pin = {}, None, None
    for line in open(LIB):
        m = re.match(r"\s*cell\s*\((\w+)\)", line)
        if m:
            cell = m.group(1)
            continue
        m = re.match(r"\s*pin\s*\((\w+)\)", line)
        if m:
            pin = m.group(1)
            continue
        m = re.match(r"\s*capacitance\s*:\s*([\d.eE+-]+)", line)
        if m and cell and pin and (cell, pin) not in caps:
            caps[(cell, pin)] = float(m.group(1))
    return caps


def read_spef():
    names, nets, cur, sect = {}, {}, None, None
    for line in open(SPEF):
        w = line.split()
        if not w:
            continue
        if sect == "map" and not line.startswith("*D_NET"):
            if w[0].startswith("*") and len(w) == 2 and w[0][1:].isdigit():
                names[w[0]] = w[1]
                continue
        if line.startswith("*NAME_MAP"):
            sect = "map"
        elif line.startswith("*D_NET"):
            cur = {"name": w[1], "conn": [], "cap": [], "res": []}
            sect = None
        elif line.startswith("*CONN"):
            sect = "conn"
        elif line.startswith("*CAP"):
            sect = "cap"
        elif line.startswith("*RES"):
            sect = "res"
        elif line.startswith("*END"):
            if cur:
                for i in cur["conn"]:
                    if i[1] == "O":
                        nets[i[0]] = cur
            cur, sect = None, None
        elif cur and sect == "conn" and w[0] == "*I":
            cur["conn"].append((w[1], w[2], w[4]))
        elif cur and sect in ("cap", "res") and w[0].isdigit():
            cur[sect].append(w[1:])
    return names, nets


def main():
    out = sys.argv[1]
    k = float(sys.argv[2]) if len(sys.argv) > 2 else 1.2
    names, nets = read_spef()
    inv = {v: k_ for k_, v in names.items()}
    caps = pin_caps()

    def real(tok):
        inst, _, pin = tok.partition(":")
        return names.get(inst, inst) + (":" + pin if pin else "")

    def node(tok):
        return "n_" + re.sub(r"[^\w]", "_", real(tok))

    lines = ["* generated by gen_bench.py, rc_scale %g" % k, cells()]
    ports = {}
    for d in DRIVERS:
        inst, pin = d.split(":")
        net = nets["%s:%s" % (inv[inst], pin)]
        lines.append("* net %s driven by %s" % (real(net["name"]), d))
        own = {c[0] for c in net["conn"]}
        for i, (a, *rest) in enumerate(net["cap"]):
            # A coupling cap is grounded at whichever end belongs to this net.
            nd = a
            if len(rest) == 2 and not (a in own or a.startswith(net["name"] + ":")):
                nd = rest[0]
            lines.append("C%s_%d %s 0 %.6g" % (node(net["name"])[2:], i, node(nd), float(rest[-1]) * k * 1e-12))
        for i, (a, b, r) in enumerate(net["res"]):
            lines.append("R%s_%d %s %s %.6g" % (node(net["name"])[2:], i, node(a), node(b), float(r) * k))
        for tok, _, cell in net["conn"]:
            inst, pin = real(tok).split(":")
            if inst in BENCH:
                ports["%s:%s" % (inst, pin)] = node(tok)
            else:
                lines.append("Cpin%s %s 0 %.6g" % (node(tok)[2:], node(tok), caps[(cell, pin)] * 1e-12))
    p = ports
    # Bench instances. Bench nodes: ck, rbl, rbc, dl (launch D), dsrc (capture D in the hold search), qc.
    lines += [
        "xcom ck vdd vdd 0 0 %s BUFX12" % p["clkbuf_1_0__f_clk_regs:Y"],
        "xl17 %s vdd vdd 0 0 %s BUFX12" % (p["clkbuf_leaf_17_clk_regs:A"], p["clkbuf_leaf_17_clk_regs:Y"]),
        "xl16 %s vdd vdd 0 0 %s BUFX12" % (p["clkbuf_leaf_16_clk_regs:A"], p["clkbuf_leaf_16_clk_regs:Y"]),
        "xlau %s dl %s rbl vdd vdd 0 0 DFFRQX1" % (p["_20056_:CK"], p["_20056_:Q"]),
        "xcap %s dcap qc rbc vdd vdd 0 0 DFFRQX1" % p["_20057_:CK"],
        # Rsw joins the launch Q net to the capture D, Rsrc the hold search source. The control script swaps them.
        "rsw %s dcap 1" % p["_20057_:D"],
        "rsrc dsrc dcap 1e12",
    ]
    lines.append("ecklau cklau 0 %s 0 1" % p["_20056_:CK"])
    lines.append("eckcap ckcap 0 %s 0 1" % p["_20057_:CK"])
    lines.append("ecom com 0 %s 0 1" % p["clkbuf_1_0__f_clk_regs:Y"])
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote %s" % out)


if __name__ == "__main__":
    main()

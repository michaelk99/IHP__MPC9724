"""Emit a LibreLane fragment that adds the thick-oxide decoupling cells.

Both the EZ130 cell library and the DECAPHV cells live outside this repo, so
their paths cannot be written as dir:: in a checked-in config. This writes a
fragment with absolute paths into <design>/runs/ and prints its path, the same
shape as the library's own librelane_scl.py.

Put it on the librelane command line AFTER the SCL fragment and BEFORE the
design config:

    librelane $(scl_frag) $(decap_frag) config.yaml

Order matters. The SCL fragment sets LIB to EZ130's three corners; this
fragment rewrites LIB to the same three corners with the decap liberty added
alongside, because a later file replaces the key rather than merging into it.
EXTRA_LIBS is the wrong tool here: it loads into every corner at once and these
cells are characterised per corner.

    decaphv_frag.py --ez130 <dir> --decap <dir> [<design dir>]

The chip top needs its own views in the same keys, because a later config file
replaces a list instead of extending it: the IO liberty per corner and the
bondpad LEF and GDS go in through --extra-lib CORNER=PATH, --extra-lef and
--extra-gds, all repeatable. The macros pass none.

    decaphv_frag.py --self-test
"""

import argparse
import os
import sys

CORNERS = [
    ("nom_typ_1p20V_25C",   "tt_1p20v_25c"),
    ("nom_fast_1p32V_m40C", "ff_1p32v_m40c"),
    ("nom_slow_1p08V_125C", "ss_1p08v_125c"),
]


def die(msg):
    sys.stderr.write("decaphv_frag: %s\n" % msg)
    sys.exit(1)


def need(path):
    if not os.path.isfile(path):
        die("missing %s" % path)
    return path


# OpenSTA refuses a library that declares no thresholds, "missing one or more
# thresholds", even one like this that carries no timing arc at all. The decap
# liberty as generated has none, so LibreLane cannot load it as a corner
# library. These are EZ130's own values, so the corner reads the same either
# way. jku-phd patched its copy in place and noted it is worth pushing
# upstream; here the copy is patched on the way past so the source stays
# untouched.
THRESHOLDS = """  input_threshold_pct_rise : 50;
  input_threshold_pct_fall : 50;
  output_threshold_pct_rise : 50;
  output_threshold_pct_fall : 50;
  slew_lower_threshold_pct_rise : 20;
  slew_lower_threshold_pct_fall : 20;
  slew_upper_threshold_pct_rise : 80;
  slew_upper_threshold_pct_fall : 80;
  slew_derate_from_library : 1;
"""


def patched_lib(src, out_dir):
    """Copy a decap liberty, adding the threshold block when it lacks one."""
    text = open(src).read()
    dst = os.path.join(out_dir, os.path.basename(src))
    if "slew_upper_threshold_pct_fall" in text:
        open(dst, "w").write(text)
        return dst
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if "time_unit" in line:
            lines.insert(i + 1, THRESHOLDS.rstrip("\n"))
            break
    else:
        die("no time_unit line in %s, cannot place the thresholds" % src)
    open(dst, "w").write("\n".join(lines))
    return dst


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ez130", required=True, help="ez130_8t_v1p1 checkout")
    ap.add_argument("--decap", required=True, help="ez130_8t_decap_hv checkout")
    ap.add_argument("--extra-lib", action="append", default=[], metavar="CORNER=PATH",
                    help="one more liberty for one corner, the chip's IO cells")
    ap.add_argument("--extra-lef", action="append", default=[], metavar="PATH")
    ap.add_argument("--extra-gds", action="append", default=[], metavar="PATH")
    ap.add_argument("design_dir", nargs="?", default=os.getcwd())
    args = ap.parse_args()

    corners = dict(CORNERS)
    extra_libs = {}
    for item in args.extra_lib:
        corner, _, path = item.partition("=")
        if corner not in corners:
            die("--extra-lib %s: no corner %s, only %s" % (item, corner, ", ".join(corners)))
        extra_libs.setdefault(corner, []).append(need(os.path.abspath(path)))
    extra_lefs = [need(os.path.abspath(f)) for f in args.extra_lef]
    extra_gds = [need(os.path.abspath(f)) for f in args.extra_gds]

    ez = os.path.abspath(args.ez130)
    hv = os.path.abspath(args.decap)

    lef = need(os.path.join(hv, "lef", "ez130_8t_decap_hv.lef"))
    gds = need(os.path.join(hv, "gds", "ez130_8t_decap_hv.gds"))
    cdl = need(os.path.join(hv, "cdl", "ez130_8t_decap_hv.cdl"))

    lib_dir = os.path.join(os.path.abspath(args.design_dir), "runs", ".decaphv_lib")
    os.makedirs(lib_dir, exist_ok=True)

    lines = [
        "# Generated by macros/scripts/decaphv_frag.py. Do not edit.",
        "# Thick-oxide decoupling cells, read in place from outside the repo.",
        "meta:",
        "  version: 2",
        "",
        "EXTRA_LEFS: [%s]" % ", ".join([lef] + extra_lefs),
        "EXTRA_GDS: [%s]" % ", ".join([gds] + extra_gds),
        "EXTRA_CDLS: [%s]" % cdl,
        "EXTRA_SPICE_MODELS: [%s]" % cdl,
        "",
        "# The full per-corner map: EZ130's own liberty plus the decap one. This",
        "# replaces what the SCL fragment set, so both have to be listed here.",
        "LIB:",
    ]
    for corner, suffix in CORNERS:
        scl_lib = need(os.path.join(ez, "lib", "ez130_8t_%s.lib" % suffix))
        hv_lib = patched_lib(
            need(os.path.join(hv, "lib", "ez130_8t_decap_hv_%s.lib" % suffix)), lib_dir)
        lines.append("  %s:" % corner)
        lines.append("    - %s" % scl_lib)
        lines.append("    - %s" % hv_lib)
        for extra in extra_libs.get(corner, []):
            lines.append("    - %s" % extra)

    out_dir = os.path.join(os.path.abspath(args.design_dir), "runs")
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, ".decaphv.yaml")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(out)


def self_test():
    """The chip passes its IO liberty and bondpad views through the fragment."""
    import subprocess
    import tempfile
    d = tempfile.mkdtemp()
    ez, hv = os.path.join(d, "ez"), os.path.join(d, "hv")
    for sub in ("lib",):
        os.makedirs(os.path.join(ez, sub))
    for sub in ("lib", "lef", "gds", "cdl"):
        os.makedirs(os.path.join(hv, sub))
    for _, suffix in CORNERS:
        open(os.path.join(ez, "lib", "ez130_8t_%s.lib" % suffix), "w").write("library(x) {\n}\n")
        open(os.path.join(hv, "lib", "ez130_8t_decap_hv_%s.lib" % suffix), "w").write(
            "library(d) {\n  time_unit : 1ns;\n}\n")
    for sub, ext in (("lef", "lef"), ("gds", "gds"), ("cdl", "cdl")):
        open(os.path.join(hv, sub, "ez130_8t_decap_hv.%s" % ext), "w").close()
    io_typ = os.path.join(d, "io_typ.lib")
    pad_lef, pad_gds = os.path.join(d, "pad.lef"), os.path.join(d, "pad.gds")
    for f in (io_typ, pad_lef, pad_gds):
        open(f, "w").close()
    design = os.path.join(d, "design")
    out = subprocess.run(
        [sys.executable, __file__, "--ez130", ez, "--decap", hv,
         "--extra-lib", "nom_typ_1p20V_25C=" + io_typ,
         "--extra-lef", pad_lef, "--extra-gds", pad_gds, design],
        check=True, capture_output=True, text=True).stdout.strip()
    text = open(out).read()
    assert "EXTRA_LEFS: [%s, %s]" % (os.path.join(hv, "lef", "ez130_8t_decap_hv.lef"), pad_lef) in text, text
    assert "EXTRA_GDS: [%s, %s]" % (os.path.join(hv, "gds", "ez130_8t_decap_hv.gds"), pad_gds) in text, text
    typ = text.split("  nom_typ_1p20V_25C:")[1].split("  nom_")[0]
    assert io_typ in typ and "ez130_8t_tt_1p20v_25c.lib" in typ, typ
    assert io_typ not in text.split("  nom_fast_1p32V_m40C:")[1], text
    bad = subprocess.run(
        [sys.executable, __file__, "--ez130", ez, "--decap", hv,
         "--extra-lib", "nom_bogus=" + io_typ, design], capture_output=True, text=True)
    assert bad.returncode != 0 and "nom_bogus" in bad.stderr, bad.stderr
    print("OK: decaphv_frag self-test")


if __name__ == "__main__":
    if sys.argv[1:] == ["--self-test"]:
        self_test()
    else:
        main()

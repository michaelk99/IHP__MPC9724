# Description: Resolve the EZ130 LibreLane fragment in place and print its path

"""LibreLane resolves `dir::` against the design directory, so
`librelane/config.yaml` cannot be passed as it is. This writes a copy with
every `dir::` pointing into this library, into `<design dir>/runs/`, and prints
its path for the command line:

    cd <macro>/flow/librelane
    librelane $(python3 <repo>/ip/ez130_8t_v1p1/scripts/librelane_scl.py) config.yaml

`runs/` is git-ignored, and the leading dot keeps the file out of LibreLane's
own `runs/*` glob, which `--last-run` would otherwise pick.

    python3 librelane_scl.py [<design dir>]      # default: the cwd
    python3 librelane_scl.py --selftest
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LL = os.path.join(os.path.dirname(HERE), "librelane")
SRC = os.path.join(LL, "config.yaml")
DIR_RX = re.compile(r"dir::(\S+?)(?=[\s,\]]|$)", re.M)


def die(msg):
    sys.stderr.write("librelane_scl: %s\n" % msg)
    sys.exit(1)


def resolve(text, base):
    """text with every dir::X outside a comment made absolute against base.

    Raises ValueError naming any file that does not exist.
    """
    missing = []

    def sub(m):
        p = os.path.normpath(os.path.join(base, m.group(1)))
        if not os.path.exists(p):
            missing.append(p)
        return p

    out = "".join(l if l.lstrip().startswith("#") else DIR_RX.sub(sub, l)
                  for l in text.splitlines(True))
    if missing:
        raise ValueError("fragment names missing files: %s" % " ".join(missing))
    return out


def selftest():
    import tempfile
    d = tempfile.mkdtemp()
    open(os.path.join(d, "a.lef"), "w").close()
    got = resolve("# dir::kept\nX: dir::a.lef\nY: [dir::a.lef, dir::a.lef]\n", d)
    want = os.path.join(d, "a.lef")
    assert got == "# dir::kept\nX: %s\nY: [%s, %s]\n" % (want, want, want), got
    try:
        resolve("X: dir::nope.lef\n", d)
    except ValueError:
        pass
    else:
        raise AssertionError("a missing file did not fail")
    real = resolve(open(SRC).read(), LL)
    assert not any("dir::" in l for l in real.splitlines()
                   if not l.lstrip().startswith("#")), "unresolved dir::"
    print("librelane_scl selftest OK")


def main():
    if sys.argv[1:] == ["--selftest"]:
        return selftest()
    design = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.getcwd())
    if not os.path.isdir(design):
        die("no design directory %s" % design)
    out = os.path.join(design, "runs", ".ez130_8t.yaml")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("# GENERATED by %s from %s. Do not edit.\n"
                % (os.path.basename(__file__), SRC))
        try:
            f.write(resolve(open(SRC).read(), LL))
        except ValueError as e:
            die(str(e))
    print(out)


if __name__ == "__main__":
    main()
